/**
 * Online account entitlement client — talks to the shared extensionsly
 * commerce backend (api.extensionsly.com), per ADR-0015. Flow: email
 * magic-code sign-in → access(1h)/refresh(30d) JWTs →
 * `GET /v1/billing/entitlement` returns an **ES256-signed entitlement
 * credential**.
 *
 * Trust model (LIC-01, licensing standard §3.2): the extension only ever
 * trusts the server-signed credential. Locally we store the credential's
 * raw token — never a bare boolean — and re-verify the signature on every
 * decision, so hand-writing storage can never grant Pro. Offline grace is
 * bounded by the credential's own `exp` (14 days at issue), not by any
 * locally-writable timestamp. A credential older than 1 day is refreshed
 * online first; if refresh fails the still-unexpired credential keeps
 * working (that IS the grace). Everything else is fail-closed.
 *
 * This Extensionsly identity is also used by the CookieVault sync service.
 * The sync Worker verifies the signed entitlement credential directly, so
 * users never have to maintain a second CookieVault-only login. Tokens are
 * device-level credentials: storage.local only, never storage.sync.
 */

import { browser } from 'wxt/browser';
import { fetchWithTimeout } from '../http.js';

const API_BASE = 'https://api.extensionsly.com';

/** Entitlement rows that unlock this product: catalog slug, or the
 * everything-bundle `ALL` (standard §5.2b). */
const PRODUCT_SLUGS = ['cookievault', 'ALL'];

// Credential-verification public key (shared across all extensionsly
// products; generated by worker/scripts/gen-entitlement-keypair.mjs).
// Standard red line: do not alter, do not mint your own.
const ENT_PUBLIC_JWK: JsonWebKey = {
  kty: 'EC',
  crv: 'P-256',
  x: 'y5BtlqtGjj5f1g0ERdldz6uSZzxqbnmKbmG6uW5DvJc',
  y: 'qHkiZmpyJsN7sX3sTxH5OYXgHPUQ9FcEOxvzi-OvMzA',
};

/** Storage keys are standard invariants (licensing.md §5.2b) — keep verbatim. */
export const ACCOUNT_SESSION_KEY = 'account.session';
export const ACCOUNT_ENTITLEMENT_KEY = 'account.entitlement'; // { token } — raw signed credential

/** Credential issued more than 1 day ago → try an online renewal first. */
const ENT_FRESH_S = 24 * 60 * 60;

export interface Session {
  access: string;
  refresh: string;
  email: string;
}

export interface EntitlementRow {
  product: string;
  tier: string;
  status: 'active' | 'canceled' | 'expired' | string;
  expires_at: number | null;
}

export interface EntTokenPayload {
  typ: string;
  iss: string;
  aud: string;
  env: string;
  sub: string;
  entitlements: EntitlementRow[];
  iat: number;
  exp: number;
}

async function api(path: string, init: RequestInit): Promise<Response> {
  return fetchWithTimeout(`${API_BASE}${path}`, {
    ...init,
    headers: { 'Content-Type': 'application/json', ...(init.headers ?? {}) },
  });
}

export async function getSession(): Promise<Session | null> {
  const raw = (await browser.storage.local.get(ACCOUNT_SESSION_KEY))[ACCOUNT_SESSION_KEY] as
    | Session
    | undefined;
  return raw &&
    typeof raw === 'object' &&
    typeof raw.access === 'string' &&
    typeof raw.refresh === 'string'
    ? raw
    : null;
}

async function setSession(s: Session | null): Promise<void> {
  if (s) await browser.storage.local.set({ [ACCOUNT_SESSION_KEY]: s });
  else await browser.storage.local.remove(ACCOUNT_SESSION_KEY);
}

/** Request an email one-time code. Backend is enumeration-safe: returns ok
 * whether or not the address exists. */
export async function requestCode(email: string): Promise<{ ok: boolean; error?: string }> {
  try {
    const r = await api('/v1/auth/magic', { method: 'POST', body: JSON.stringify({ email }) });
    const body = (await r.json().catch(() => ({}))) as { error?: string };
    return r.ok ? { ok: true } : { ok: false, error: body.error ?? `http_${r.status}` };
  } catch {
    return { ok: false, error: 'network' };
  }
}

/** Sign in with the emailed code; on success immediately pull a credential. */
export async function signIn(
  email: string,
  code: string,
): Promise<{ ok: boolean; error?: string }> {
  try {
    const r = await api('/v1/auth/verify', {
      method: 'POST',
      body: JSON.stringify({ email, code }),
    });
    const body = (await r.json().catch(() => ({}))) as {
      access?: string;
      refresh?: string;
      email?: string;
      error?: string;
    };
    if (!r.ok || !body.access || !body.refresh) {
      return { ok: false, error: body.error ?? `http_${r.status}` };
    }
    await setSession({ access: body.access, refresh: body.refresh, email: body.email ?? email });
    await refreshEntitlement();
    return { ok: true };
  } catch {
    return { ok: false, error: 'network' };
  }
}

export async function signOut(): Promise<void> {
  await setSession(null);
  await browser.storage.local.remove(ACCOUNT_ENTITLEMENT_KEY);
}

function b64urlToBytes(s: string): Uint8Array {
  const b64 = s.replace(/-/g, '+').replace(/_/g, '/') + '='.repeat((4 - (s.length % 4)) % 4);
  const bin = atob(b64);
  const out = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) out[i] = bin.charCodeAt(i);
  return out;
}

function jwtExp(token: string): number {
  try {
    const part = token.split('.')[1] ?? '';
    const payload = JSON.parse(atob(part.replace(/-/g, '+').replace(/_/g, '/'))) as {
      exp?: unknown;
    };
    return typeof payload.exp === 'number' ? payload.exp : 0;
  } catch {
    return 0;
  }
}

/** Usable access token; renews via refresh when stale. A revoked/expired
 * refresh ends the session; transient server errors do NOT sign out. */
async function accessToken(): Promise<string | null> {
  const s = await getSession();
  if (!s) return null;
  if (jwtExp(s.access) - 60 > Date.now() / 1000) return s.access;
  try {
    const r = await api('/v1/auth/refresh', {
      method: 'POST',
      body: JSON.stringify({ refresh: s.refresh }),
    });
    if (r.status === 401) {
      await signOut();
      return null;
    }
    const body = (await r.json().catch(() => ({}))) as { access?: string };
    if (!r.ok || !body.access) return null;
    await setSession({ ...s, access: body.access });
    return body.access;
  } catch {
    return null;
  }
}

let entKeyPromise: Promise<CryptoKey> | null = null;
function getEntKey(): Promise<CryptoKey> {
  entKeyPromise ??= crypto.subtle.importKey(
    'jwk',
    ENT_PUBLIC_JWK,
    { name: 'ECDSA', namedCurve: 'P-256' },
    false,
    ['verify'],
  );
  return entKeyPromise;
}

/**
 * Verify an entitlement credential. Signature, `typ`, `iss`, `exp` or a
 * from-the-future `iat` — any mismatch returns null (fail-closed).
 * The key is injectable so tests can use a throwaway keypair; production
 * callers omit it and get the embedded extensionsly public key.
 */
export async function verifyEntToken(
  token: string,
  publicKey?: CryptoKey,
): Promise<EntTokenPayload | null> {
  const parts = token.split('.');
  if (parts.length !== 3) return null;
  try {
    const header = JSON.parse(
      new TextDecoder().decode(b64urlToBytes(parts[0] ?? '')),
    ) as { alg?: unknown; typ?: unknown };
    if (header.alg !== 'ES256' || header.typ !== 'JWT') return null;
    const sig = b64urlToBytes(parts[2] ?? '');
    const data = new TextEncoder().encode(`${parts[0]}.${parts[1]}`);
    const ok = await crypto.subtle.verify(
      { name: 'ECDSA', hash: 'SHA-256' },
      publicKey ?? (await getEntKey()),
      sig as unknown as BufferSource,
      data as unknown as BufferSource,
    );
    if (!ok) return null;
    const payload = JSON.parse(
      new TextDecoder().decode(b64urlToBytes(parts[1] ?? '')),
    ) as EntTokenPayload;
    const nowSec = Date.now() / 1000;
    if (payload.typ !== 'entitlement' || payload.iss !== 'exly'
        || payload.aud !== 'extensionsly-entitlement-production'
        || payload.env !== 'production'
        || typeof payload.sub !== 'string' || payload.sub.length < 1
        || !Array.isArray(payload.entitlements)) return null;
    if (typeof payload.exp !== 'number' || nowSec >= payload.exp) return null;
    if (typeof payload.iat !== 'number' || payload.iat > nowSec + 300) return null;
    return payload;
  } catch {
    return null;
  }
}

/** Does one entitlement row unlock this product right now? Only an active row
 * entitles; canceled, expired and unknown states fail closed. */
export function rowEntitles(row: EntitlementRow, nowSec: number = Date.now() / 1000): boolean {
  if (!PRODUCT_SLUGS.includes(row.product)) return false;
  if (row.expires_at && nowSec > row.expires_at) return false;
  return row.status === 'active';
}

function decide(payload: EntTokenPayload): boolean {
  return (payload.entitlements ?? []).some((row) => rowEntitles(row));
}

/** Raw stored credential, if any. Also consumed by the sync client, which
 * forwards it to the CookieVault worker's Pro gate (ADR-0015). */
export async function getStoredEntToken(): Promise<string | null> {
  const raw = (await browser.storage.local.get(ACCOUNT_ENTITLEMENT_KEY))[
    ACCOUNT_ENTITLEMENT_KEY
  ] as { token?: string } | undefined;
  return typeof raw?.token === 'string' ? raw.token : null;
}

/** Fetch a fresh credential, verify, persist. Returns null on any failure —
 * network, backend without a signing key, bad signature (callers then fall
 * back to the stored, still-unexpired credential: the grace path). */
export async function refreshEntitlement(): Promise<EntTokenPayload | null> {
  const token = await accessToken();
  if (!token) return null;
  try {
    const r = await api('/v1/billing/entitlement', {
      method: 'GET',
      headers: { Authorization: `Bearer ${token}` },
    });
    if (!r.ok) return null;
    const body = (await r.json()) as { token?: string | null };
    if (typeof body.token !== 'string') return null; // backend unsigned → trust nothing
    const payload = await verifyEntToken(body.token);
    if (!payload) return null;
    await browser.storage.local.set({ [ACCOUNT_ENTITLEMENT_KEY]: { token: body.token } });
    return payload;
  } catch {
    return null;
  }
}

/**
 * Online Pro decision — only ever from a signature-verified credential.
 * Fresh (≤1 day old) credentials are trusted directly; stale ones renew
 * online first; if renewal fails, an unexpired stored credential still
 * counts (grace ceiling = its own `exp`). No valid credential → false.
 */
export async function getOnlinePro(): Promise<boolean> {
  const stored = await getStoredEntToken();
  const payload = stored ? await verifyEntToken(stored) : null;
  if (payload && Date.now() / 1000 - payload.iat < ENT_FRESH_S) return decide(payload);
  const fresh = await refreshEntitlement();
  if (fresh) return decide(fresh);
  return payload ? decide(payload) : false;
}

export interface TrialResult {
  ok: boolean;
  error?: string;
  /** true = newly started; false = this account already had a record (trial
   * or paid) and it was returned as-is — never renewed or downgraded. */
  started?: boolean;
  expiresAt?: number | null;
}

/**
 * Email-gated 14-day trial (licensing standard §3.4): one per account per
 * product, for life. State lives on the server (bound to the account), so
 * uninstall/reinstall or clearing storage can't re-farm it — the exact failure
 * mode a local trial clock can't prevent. On success the fresh signed
 * credential is stored and Pro takes effect immediately; if the account already
 * used its trial, the existing (possibly expired) record is returned unchanged.
 */
export async function startTrial(): Promise<TrialResult> {
  const token = await accessToken();
  if (!token) return { ok: false, error: 'not_signed_in' };
  try {
    const r = await api('/v1/trial/start', {
      method: 'POST',
      headers: { Authorization: `Bearer ${token}` },
      body: JSON.stringify({ product: PRODUCT_SLUGS[0] }),
    });
    const body = (await r.json().catch(() => ({}))) as {
      started?: boolean;
      entitlement?: { expires_at?: number | null };
      token?: string | null;
      error?: string;
    };
    if (!r.ok) return { ok: false, error: body.error ?? `http_${r.status}` };
    // Only persist a credential that verifies — same trust rule as everywhere.
    if (typeof body.token === 'string' && (await verifyEntToken(body.token))) {
      await browser.storage.local.set({ [ACCOUNT_ENTITLEMENT_KEY]: { token: body.token } });
    }
    return { ok: true, started: !!body.started, expiresAt: body.entitlement?.expires_at ?? null };
  } catch {
    return { ok: false, error: 'network' };
  }
}

/** Invoke `cb` whenever the session or the stored credential changes. */
export function onAccountChanged(cb: () => void): void {
  browser.storage.onChanged.addListener((changes, area) => {
    if (
      area === 'local' &&
      (ACCOUNT_SESSION_KEY in changes || ACCOUNT_ENTITLEMENT_KEY in changes)
    ) {
      cb();
    }
  });
}
